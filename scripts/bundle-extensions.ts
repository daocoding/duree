import { writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { loadConfig, type LoadedConfig } from "../config/load";

/** Rewrite extensions/bundle.ts from config. An empty list registers nothing. */
export function writeExtensionBundle(loaded: LoadedConfig, overlayDir?: string): string {
  const specs = loaded.config.extensions ?? [];
  const base = overlayDir ? resolve(loaded.root, overlayDir) : loaded.root;
  const bundlePath = resolve(loaded.root, "extensions/bundle.ts");
  const lines = ["/** Generated by `npm run bundle-extensions`. The default bundle registers nothing. */"];
  if (specs.length === 0) {
    lines.push("export {};");
  } else {
    lines.push('import { registerExtension } from "../core/extend";');
    specs.forEach((spec, index) => {
      const absolute = resolve(base, spec);
      let fromBundle = relative(dirname(bundlePath), absolute).replaceAll("\\", "/");
      if (!fromBundle.startsWith(".")) fromBundle = `./${fromBundle}`;
      lines.push(`import ext${index} from "${fromBundle}";`);
      lines.push(`registerExtension(ext${index});`);
    });
  }
  writeFileSync(bundlePath, `${lines.join("\n")}\n`);
  return bundlePath;
}

function isDirectRun(): boolean {
  const entry = process.argv[1];
  return !!entry && import.meta.url === pathToFileURL(entry).href;
}

if (isDirectRun()) {
  const overlayFlag = process.argv.indexOf("--overlay");
  const overlay = overlayFlag >= 0 ? process.argv[overlayFlag + 1] : undefined;
  const loaded = loadConfig({ overlayDir: overlay });
  const path = writeExtensionBundle(loaded, overlay);
  console.log(`wrote ${path}`);
}
